"""
Translation Manager - Handles multi-language support
"""

from pathlib import Path
from typing import Dict
from PySide6.QtCore import (
    QObject, Signal, QTranslator, QCoreApplication, QEvent, QLibraryInfo,
)
from settings.settings_manager import SettingsManager
from core.paths import resource_path


class TranslationManager(QObject):
    """Manages application translations"""

    language_changed = Signal(str)

    # Supported languages
    LANGUAGES = {
        "ar": {"name": "العربية", "native": "العربية", "code": "ar", "locale": "ar_SA"},
        "en": {"name": "English", "native": "English", "code": "en", "locale": "en_US"},
        "it": {"name": "Italiano", "native": "Italiano", "code": "it", "locale": "it_IT"},
        "es": {"name": "Español", "native": "Español", "code": "es", "locale": "es_ES"},
        "pt": {"name": "Português (Brasil)", "native": "Português (Brasil)", "code": "pt", "locale": "pt_BR"},
        "tr": {"name": "Türkçe", "native": "Türkçe", "code": "tr", "locale": "tr_TR"},
    }

    def __init__(self, settings_manager: SettingsManager):
        super().__init__()
        self.settings = settings_manager
        # Complete, per-language catalogue generated by tools/build_translations.py.
        # Every string the application uses is present in every language, so the
        # UI is never half translated and reads consistently across languages.
        self.translator = QTranslator()
        # Legacy catalogues, only used as a fall-back for a language that has no
        # complete catalogue yet.
        self.legacy_translator = QTranslator()
        self.extra_translator = QTranslator()
        # Qt's own catalogue, which localizes built-in widget strings such as
        # the OK / Cancel / Apply buttons of QDialogButtonBox and the standard
        # message boxes.  Installed with the lowest priority.
        self.qt_translator = QTranslator()
        self.current_language = "ar"
        self.translations_path = resource_path("translations")
        self._load_current_language()

    def _load_current_language(self):
        """Load current language from settings"""
        self.current_language = self.settings.get_language()
        self.apply_language(self.current_language)

    def get_available_languages(self) -> Dict[str, Dict[str, str]]:
        """Get list of available languages"""
        return self.LANGUAGES

    def get_current_language(self) -> str:
        """Get current language code"""
        return self.current_language

    def get_language_name(self, code: str) -> str:
        """Get language name in its native form"""
        return self.LANGUAGES.get(code, {}).get("native", code)

    def apply_language(self, language_code: str) -> bool:
        """Apply language to application"""
        if language_code not in self.LANGUAGES:
            return False

        # Remove current translators
        QCoreApplication.removeTranslator(self.translator)
        QCoreApplication.removeTranslator(self.legacy_translator)
        QCoreApplication.removeTranslator(self.extra_translator)
        QCoreApplication.removeTranslator(self.qt_translator)

        locale = self.LANGUAGES[language_code]["locale"]

        # Qt's own catalogue (standard widgets: OK / Cancel / Apply, ...).
        # Installed first so the application catalogues take precedence.
        self._load_qt_translator(locale, language_code)

        loaded = False
        # Preferred: the complete catalogue (msmp_<locale>.qm).
        complete_file = self.translations_path / f"msmp_{locale}.qm"
        if language_code == "en":
            # English is the source language: the strings already *are* English,
            # so installing a catalogue is unnecessary (and would only risk
            # shipping an accidental mistranslation).
            loaded = True
        elif complete_file.exists() and self.translator.load(str(complete_file)):
            QCoreApplication.installTranslator(self.translator)
            loaded = True
        else:
            # Fall back to the legacy split catalogues for this language.
            legacy_file = self.translations_path / f"app_{locale}.qm"
            if legacy_file.exists() and self.legacy_translator.load(str(legacy_file)):
                QCoreApplication.installTranslator(self.legacy_translator)
                extra_file = self.translations_path / f"extra_{locale}.qm"
                if extra_file.exists() and self.extra_translator.load(str(extra_file)):
                    QCoreApplication.installTranslator(self.extra_translator)
                loaded = True

        if not loaded and language_code != "en":
            # Fallback to English if no catalogue is available.
            return self.apply_language("en")

        self.current_language = language_code
        self.settings.set_language(language_code)
        self._broadcast_language_change()
        return True

    def _load_qt_translator(self, locale: str, language_code: str):
        """Load Qt's stock translations (standard button/dialog strings)."""
        candidates = [f"qtbase_{locale}", f"qt_{locale}", f"qt_{language_code}"]
        for name in candidates:
            path = self._qt_translations_dir() / f"{name}.qm"
            try:
                if path.exists() and self.qt_translator.load(str(path)):
                    QCoreApplication.installTranslator(self.qt_translator)
                    return
            except Exception:
                continue

    def _qt_translations_dir(self) -> Path:
        """Directory that holds Qt's own ``.qm`` catalogues."""
        try:
            path = QLibraryInfo.path(QLibraryInfo.LibraryPath.TranslationsPath)
            if path:
                return Path(path)
        except Exception:
            pass
        # Fall back to the PySide6 installation directory.
        try:
            import PySide6
            return Path(PySide6.__file__).parent / "translations"
        except Exception:
            return Path()

    def _broadcast_language_change(self):
        """Notify the rest of the application that the language changed.

        Emits the ``language_changed`` signal and posts a Qt
        ``LanguageChange`` event to every top-level widget, which triggers
        ``changeEvent()`` / any custom ``retranslate()`` handlers so the whole
        UI updates instantly without restarting the application.
        """
        self.language_changed.emit(self.current_language)

        app = QCoreApplication.instance()
        if app is None:
            return
        try:
            event = QEvent(QEvent.Type.LanguageChange)
            for widget in app.topLevelWidgets():
                if widget is not None:
                    QCoreApplication.sendEvent(widget, event)
        except Exception:
            pass

    def translate(self, context: str, text: str, disambiguation: str = None, n: int = -1) -> str:
        """Translate text with fallback to source"""
        result = QCoreApplication.translate(context, text, disambiguation, n)
        # Fallback to source text if translation is empty
        return result if result else text


# Global translation function with fallback
def qt_translate(context: str, text: str, disambiguation: str = None, n: int = -1) -> str:
    """Translation function for non-QObject classes with fallback"""
    result = QCoreApplication.translate(context, text, disambiguation, n)
    return result if result else text