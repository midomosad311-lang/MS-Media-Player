"""Generate ``packaging/eula_text.iss`` from the per-language EULA documents.

The License Agreement page of the installer displays the EULA from *embedded*
Pascal procedures rather than reading a file at run time.  That removes any
dependency on where ``Setup.exe`` is located and, more importantly, on the text
encoding: the ``.iss`` source is UTF-8 (Inno Setup 6 reads it correctly), so the
Arabic text is always rendered exactly as written.

One procedure is generated per installer language and a dispatcher picks the
right one from the language the user selected at the start of the setup, so the
licence is always shown in the language the user chose.

Sources:

    packaging/eula/EULA_ar.txt   (Arabic)
    packaging/eula/EULA_en.txt   (English)
    packaging/eula/EULA_it.txt   (Italian)
    packaging/eula/EULA_es.txt   (Spanish)
    packaging/eula/EULA_pt.txt   (Portuguese)
    packaging/eula/EULA_tr.txt   (Turkish)

Run after editing any of those files:

    python tools/make_eula_iss.py
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EULA_DIR = ROOT / "packaging" / "eula"
OUT = ROOT / "packaging" / "eula_text.iss"

# installer language name -> (source file suffix, procedure suffix)
LANGUAGES = [
    ("english", "en", "en"),
    ("arabic", "ar", "ar"),
    ("italian", "it", "it"),
    ("spanish", "es", "es"),
    ("portuguese", "pt", "pt"),
    ("turkish", "tr", "tr"),
]


def pascal_literal(text: str) -> str:
    """Encode *text* as a single-quoted Pascal string literal."""
    return "'" + text.replace("'", "''") + "'"


def main() -> int:
    out = [
        "{ ------------------------------------------------------------------ }",
        "{  AUTO-GENERATED by tools/make_eula_iss.py.                          }",
        "{  Do not edit by hand - edit packaging/eula/EULA_<lang>.txt and     }",
        "{  regenerate instead.                                                }",
        "{ ------------------------------------------------------------------ }",
        "",
    ]

    total = 0
    for _lang_name, suffix, proc in LANGUAGES:
        src = EULA_DIR / f"EULA_{suffix}.txt"
        lines = src.read_text(encoding="utf-8").splitlines()
        total += len(lines)
        out.append(f"procedure LoadEula_{proc}(Memo: TNewMemo);")
        out.append("begin")
        for line in lines:
            out.append(f"  Memo.Lines.Add({pascal_literal(line)});")
        out.append("end;")
        out.append("")

    # Dispatcher: choose the agreement for the language the user selected.
    out.append("procedure LoadEmbeddedEula(Memo: TNewMemo);")
    out.append("begin")
    first = True
    for lang_name, _suffix, proc in LANGUAGES:
        if proc == "en":
            continue
        keyword = "if" if first else "else if"
        first = False
        out.append(f"  {keyword} ActiveLanguage = '{lang_name}' then")
        out.append(f"    LoadEula_{proc}(Memo)")
    out.append("  else")
    out.append("    LoadEula_en(Memo);")
    out.append("end;")
    out.append("")

    # utf-8-sig: Inno Setup 6 always detects a UTF-8 script by its BOM, which
    # guarantees the Arabic text is read correctly.
    OUT.write_text("\n".join(out), encoding="utf-8-sig")
    print(f"Wrote {OUT} ({len(LANGUAGES)} languages, {total} text lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
